"""Единые настройки проекта: пути к данным, артефактам и порог spam/ham.

Модуль лежит в common/, потому что его читают все слои, а он не должен
зависеть ни от одного из них: только константы, ни одного импорта. Всё, что
раньше дублировалось константами в четырёх файлах, живёт здесь.

Про порог. Каждая модель получает свою рабочую точку: порог подбирается по f1
на val, метрики на test считаются при нём. Поэтому SPAM_THRESHOLD — это не
«правильное число», а порог модели, победившей в бенчмарке; какое именно
значение поставить, печатает scripts/compare.py.

Осторожно с именем: значение относится к той модели, чьи метрики выиграли, а
service/api.py всегда обслуживает RuBERT. Сейчас выиграла RuBERT (f1 = 0.9089
против 0.9058 у baseline), поэтому перенос константы здесь достаточен. Если
baseline обойдёт RuBERT, одной правки константы мало: сервис придётся
переключить на линейную модель, иначе порог победителя уйдёт RuBERT.
"""

# Порог обслуживаемой модели. Каждая модель подбирает его сама по f1 на val, и
# печатает его scripts/compare.py. Значение ниже взято из бенчмарка:
# RuBERT f1 = 0.9089 на test при пороге 0.1 против 0.9058 у baseline при 0.65.
# Порог очень низкий, потому что после fine-tune модель уверенно разделяет
# классы и максимум f1 лежит в начале шкалы; правило выбора — строгий
# максимум f1, при равенстве берётся меньший порог.
SPAM_THRESHOLD = 0.1

# Данные. train_split и val_split — части одной разбивки, test к ней не
# входит: на test модели отчитываются один раз и больше не подбираются.
# Файла train.csv (train_split + val_split) здесь нет намеренно: обучение на
# нём сломало бы равенство моделей, у одной было бы на 17% больше данных.
DATA_DIR = "model/data"
TRAIN_CSV = f"{DATA_DIR}/train_split.csv"
VAL_CSV = f"{DATA_DIR}/val_split.csv"
TEST_CSV = f"{DATA_DIR}/test.csv"
CACHE_DIR = f"{DATA_DIR}/cache"

CHECKPOINT_DIR = "model/checkpoints"
CHECKPOINT_PATH = f"{CHECKPOINT_DIR}/best.pt"

MODEL_NAME = "DeepPavlov/rubert-base-cased"

# Длина, до которой обрезается письмо, в токенах. 128 было мало: у писем
# медиана 291 токен, среднее 513, а девять из десяти длиннее 1000, поэтому
# при 128 модель читала только верхнюю четверть письма, тогда как baseline
# работает с текстом целиком. Сравнение было несимметричным. 512 покрывает
# около 85% письма, и это укладывается в разумное время обучения на GPU.
MAX_LENGTH = 512

# Зерно генератора случайных чисел. Без него два прогона RuBERT не сравнить
# между собой: и перемешивание батчей, и инициализация головы случайны.
SEED = 42

# Размер словаря TF-IDF в baseline. К самой модели он отношения не имеет:
# словарь задаёт TfidfVectorizer.
MAX_FEATURES = 10000

# Сетка силы регуляризации для baseline. Перебор идёт по val, и лучший C
# играет ту же роль, что и выбранная эпоха у RuBERT: это отбор модели на
# отложенной выборке, а не настройка по test.
C_GRID = (0.1, 0.5, 1.0, 2.0, 4.0, 8.0)

# Словарь меток. Отсюда его берёт model/data/labels.py, поэтому переименование
# класса нельзя выполнить в одном месте, забыв другое.
LABELS = ("ham", "spam")

# Доли метрик: именно они попадают на графики. tp/fp/tn/fn — целые счётчики,
# на шкале [0, 1] они сломали бы разметку, поэтому в список не входят.
METRIC_NAMES = ("precision", "recall", "f1", "accuracy")

# Артефакты бенчмарка: их читает scripts/compare.py, поэтому имена общие.
BASELINE_METRICS_CSV = "baseline_metrics.csv"
BASELINE_PREDICTIONS_CSV = "baseline_predictions.csv"
BASELINE_PLOT = "baseline_metrics.png"
RUBERT_METRICS_CSV = "rubert_metrics.csv"
RUBERT_PLOT = "rubert_metrics.png"
COMPARISON_CSV = "comparison_metrics.csv"
COMPARISON_PLOT = "comparison.png"